def finish(x):
    """Remove DC, short fades, normalise to TARGET_RMS_DB (loudest half of 20 ms frames), cap peaks at -1 dBFS."""
    x = np.nan_to_num(np.asarray(x, dtype=np.float64))
    if len(x) == 0:
        return np.zeros(int(0.1 * SR))
    x = x - np.mean(x)
    fi = min(len(x) // 4, int(0.002 * SR))
    fo = min(len(x) // 4, int(0.015 * SR))
    if fi > 0:
        x[:fi] *= np.linspace(0.0, 1.0, fi)
    if fo > 0:
        x[-fo:] *= np.linspace(1.0, 0.0, fo)
    frame = 960
    m = len(x) // frame
    if m >= 2:
        rms = np.sqrt(np.mean(x[: m * frame].reshape(m, frame) ** 2, axis=1))
        top = np.sort(rms)[m // 2:]
        level = float(np.sqrt(np.mean(top ** 2)))
    else:
        level = float(np.sqrt(np.mean(x ** 2)))
    peak = float(np.max(np.abs(x)))
    if level < 1e-9 or peak < 1e-9:
        return x
    g = min(10 ** (TARGET_RMS_DB / 20) / level, CEILING / peak)
    return x * g


def generate(name):
    fn = SOUNDS[name][0]
    return finish(fn())


def render_all(out_dir):
    """Write every sound to <out_dir>/wav/<name>.wav plus catalogue.json. Returns [(entry, samples)]."""
    out_dir = Path(out_dir)
    wav = out_dir / "wav"
    wav.mkdir(parents=True, exist_ok=True)
    res = []
    for name, (_fn, category, desc) in SOUNDS.items():
        x = generate(name)
        sf.write(str(wav / f"{name}.wav"), x.astype(np.float32), SR, subtype="PCM_16")
        entry = {
            "name": name,
            "file": f"wav/{name}.wav",
            "category": category,
            "description": desc,
            "durationSec": round(len(x) / SR, 3),
            "licence": LICENCE,
        }
        res.append((entry, x))
        print(f"sfx {name:20s} {entry['durationSec']:5.2f}s  {category}", flush=True)
    cat = {"generator": "pipeline/sfxlib.py", "sampleRate": SR, "targetRmsDb": TARGET_RMS_DB, "peakCeilingDb": -1.0,
           "licence": LICENCE, "sounds": [e for e, _ in res]}
    with open(out_dir / "catalogue.json", "w", encoding="utf-8") as f:
        json.dump(cat, f, indent=2)
        f.write("\n")
    return res


