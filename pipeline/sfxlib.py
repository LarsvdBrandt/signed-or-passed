# ----------------------------------------------------------------------------------------------- building blocks

def T(dur):
    return np.arange(int(round(dur * SR))) / SR


def silence(dur):
    return np.zeros(int(round(dur * SR)))


def noise(dur, seed=0):
    return np.random.default_rng(seed).uniform(-1.0, 1.0, int(round(dur * SR)))


def filt(x, lo=None, hi=None, order=4):
    """Zero-phase FFT filter: high-pass at lo Hz and/or low-pass at hi Hz (Butterworth-like magnitude)."""
    n = len(x)
    if n == 0:
        return x
    X = np.fft.rfft(x)
    f = np.maximum(np.fft.rfftfreq(n, 1.0 / SR), 1e-3)
    m = np.ones_like(f)
    if lo:
        m *= 1.0 / np.sqrt(1.0 + (lo / f) ** (2 * order))
    if hi:
        m *= 1.0 / np.sqrt(1.0 + (f / hi) ** (2 * order))
    return np.fft.irfft(X * m, n=n)


def band(x, f0, q=4.0):
    """Band-pass around f0: a Gaussian bump on the log-frequency axis (q = sharpness, 1 = about 2 octaves wide)."""
    n = len(x)
    if n == 0:
        return x
    X = np.fft.rfft(x)
    f = np.maximum(np.fft.rfftfreq(n, 1.0 / SR), 1e-3)
    m = np.exp(-0.5 * (np.log2(f / f0) * q) ** 2)
    return np.fft.irfft(X * m, n=n)


def osc(freq, dur=None, kind="sine", phase=0.0):
    """Oscillator. freq is a number (then dur is required) or an array of per-sample frequencies (glides)."""
    if np.isscalar(freq):
        freq = np.full(int(round(dur * SR)), float(freq))
    ph = 2 * np.pi * np.cumsum(freq) / SR + phase
    if kind == "sine":
        return np.sin(ph)
    cyc = (ph / (2 * np.pi)) % 1.0
    if kind == "square":
        return np.where(cyc < 0.5, 1.0, -1.0)
    if kind == "saw":
        return 2.0 * cyc - 1.0
    if kind == "tri":
        return 2.0 * np.abs(2.0 * cyc - 1.0) - 1.0
    raise ValueError(kind)


def glide(f0, f1, dur, curve="exp"):
    p = T(dur) / max(dur, 1e-9)
    if curve == "exp":
        return f0 * (f1 / f0) ** p
    return f0 + (f1 - f0) * p


def decay(dur, k):
    return np.exp(-k * T(dur))


def ar(dur, attack, release=None):
    """Linear attack, flat, linear release over the last `release` seconds (default: the whole remainder)."""
    t = T(dur)
    a = np.clip(t / max(attack, 1e-4), 0.0, 1.0)
    rel = release if release is not None else max(dur - attack, 1e-4)
    r = np.clip((dur - t) / max(rel, 1e-4), 0.0, 1.0)
    return a * r


def mix(*parts):
    """Sum arrays of different lengths (zero-padded)."""
    n = max(len(p) for p in parts)
    out = np.zeros(n)
    for p in parts:
        out[: len(p)] += p
    return out


def place(dst, src, at):
    """Mix src into dst starting at `at` seconds (clipped to dst)."""
    i = int(round(at * SR))
    if i >= len(dst) or i < 0:
        return dst
    j = min(len(dst), i + len(src))
    dst[i:j] += src[: j - i]
    return dst


def sweep_noise(dur, f0, f1, seed=0, bands=10, q=2.0):
    """Noise whose centre frequency glides from f0 to f1 (crossfaded band-passes)."""
    n = noise(dur, seed)
    p = T(dur) / max(dur, 1e-9)
    out = np.zeros_like(n)
    centres = f0 * (f1 / f0) ** np.linspace(0, 1, bands)
    pos = p * (bands - 1)
    for i, fc in enumerate(centres):
        w = np.clip(1 - np.abs(pos - i), 0, 1)
        out += band(n, fc, q) * w
    return out


def bell(freq, dur, k=3.0, partials=((1, 1.0), (2.76, 0.5), (5.4, 0.25), (8.93, 0.12))):
    t = T(dur)
    out = np.zeros_like(t)
    for ratio, amp in partials:
        out += amp * np.sin(2 * np.pi * freq * ratio * t) * np.exp(-k * ratio ** 0.5 * t)
    return out


def click(dur=0.006, lo=1500, hi=9000, seed=0):
    return filt(noise(dur, seed), lo, hi) * decay(dur, 600)


def thump(freq=60, dur=0.25, k=18, f_drop=1.6):
    return osc(glide(freq * f_drop, freq, dur)) * decay(dur, k)


def marimba(freq, dur=0.35):
    t = T(dur)
    return (np.sin(2 * np.pi * freq * t) + 0.25 * np.sin(2 * np.pi * freq * 4 * t) * np.exp(-30 * t)) * np.exp(-9 * t)


def snare(seed, d=0.12):
    return filt(noise(d, seed), 1500, 9000) * decay(d, 35) * 0.8 + osc(glide(240, 180, d)) * decay(d, 40) * 0.5


